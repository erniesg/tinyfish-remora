import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { catalog, fixtureMarket } from "../src/lib/purchases/catalog";

const wall = (date: Date) => new Intl.DateTimeFormat("sv-SE", { timeZone: "Asia/Singapore", year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", hourCycle: "h23" }).format(date).replace(" ", "T");

test("bounded purchase persists, arms, executes in a worker and recovers without duplicate submission", async ({ page, request }) => {
  test.setTimeout(120000); // Includes two independently compiled worker process runs.
  test.skip(process.env.REMORA_PURCHASE_MODE !== "mock", "Run npm run test:purchases:ui for an isolated local mock service.");
  const pageErrors: string[] = [];
  page.on("pageerror", e => pageErrors.push(e.message));
  await page.goto("/auth");
  await page.getByRole("button", { name: /Create demo account|Enter demo cockpit/ }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.getByRole("link", { name: "Buy shares" }).click();
  await expect(page.getByRole("heading", { name: "Plan a share purchase" })).toBeVisible();
  await page.getByLabel("Whole shares").fill("2");
  await page.getByLabel("Limit per share (USD)").fill("101");
  await page.getByLabel("Total spending ceiling (USD)").fill("206");
  let selectedStart = new Date(Date.now() - 120000);
  for (let n = 0; n < 14 * 48 && !fixtureMarket(catalog[0], selectedStart).open; n++) selectedStart = new Date(selectedStart.getTime() + 1800000);
  expect(fixtureMarket(catalog[0], selectedStart).open).toBe(true);
  await page.getByLabel("Purchase after").fill(wall(selectedStart));
  await page.getByLabel("Stop if unfilled by").fill(wall(new Date(selectedStart.getTime() + 3600000)));
  let releasePreview!: () => void;
  const previewGate = new Promise<void>(resolve => { releasePreview = resolve; });
  const delayPreview = async (route: import("@playwright/test").Route) => {
    if (route.request().method() === "POST" && route.request().postDataJSON().action === "preview") await previewGate;
    await route.continue();
  };
  await page.route("**/api/purchases", delayPreview);
  await page.getByRole("button", { name: "Preview purchase", exact: true }).click();
  await expect(page.getByLabel("Whole shares")).toBeDisabled();
  await expect(page.getByLabel("Company and listing")).toBeDisabled();
  await expect(page.getByRole("button", { name: "Stop all purchases", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "Refresh status", exact: true }).click();
  await expect(page.getByLabel("Whole shares")).toBeDisabled();
  releasePreview();
  await expect(page.getByText("This purchase cannot be armed yet.", { exact: true })).toBeVisible();
  await page.unroute("**/api/purchases", delayPreview);
  await expect(page.getByText(/Maximum spend must cover/)).toBeVisible();
  await page.getByLabel("Total spending ceiling (USD)").fill("207");
  await expect(page.getByRole("button", { name: "Save purchase", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Preview purchase", exact: true }).click();
  await expect(page.getByText("Within the simulation's supported limits.")).toBeVisible();
  await page.getByRole("button", { name: "Save purchase", exact: true }).click();
  const appleCard = page.locator("article").filter({ has: page.getByRole("heading", { name: "2 × Apple", exact: true }) });
  await expect(appleCard).toContainText("NASDAQ · Common · USD");
  await expect(appleCard).toContainText("not an opening auction");
  await appleCard.getByRole("button", { name: "Edit draft", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Edit inactive draft", exact: true })).toBeVisible();
  await expect(page.getByLabel("Whole shares")).toHaveValue("2");
  await expect(page.getByLabel("Limit per share (USD)")).toHaveValue("101");
  await expect(page.getByLabel("Total spending ceiling (USD)")).toHaveValue("207");
  await expect(page.getByLabel("Purchase after")).toHaveValue(wall(selectedStart));
  await expect(appleCard.getByRole("button", { name: "Arm simulation", exact: true })).toBeDisabled();
  await page.getByLabel("Limit per share (USD)").fill("102");
  await page.getByLabel("Total spending ceiling (USD)").fill("209");
  await expect(page.getByRole("button", { name: "Save draft changes", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Preview purchase", exact: true }).click();
  await page.getByRole("button", { name: "Save draft changes", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Set purchase limits", exact: true })).toBeVisible();
  const revised = await (await request.get("/api/purchases")).json();
  expect(revised.purchases).toHaveLength(1);
  expect(revised.purchases[0].revision).toBe(1);
  const staleArm = await request.post(`/api/purchases/${revised.purchases[0].id}`, { data: { action: "arm", expectedRevision: 0 } });
  expect(staleArm.status()).toBe(409);
  await appleCard.getByRole("button", { name: "Arm simulation", exact: true }).click();
  await expect(page.getByText("armed", { exact: true })).toBeVisible();
  const before = await (await request.get("/api/purchases")).json();
  expect(before.purchases).toHaveLength(1);
  expect(before.purchases[0].reserved).toBe(209);
  // Actual local worker, same private durable database; no intercepted browser requests.
  execFileSync("bash", ["scripts/purchases.sh", "worker", "--once"], { env: process.env, timeout: 60000 });
  await page.reload();
  const after = await (await request.get("/api/purchases")).json();
  const purchase = after.purchases[0];
  // The real current session may be closed. Backend deterministic tests cover fills,
  // holidays, DST, delayed listing and partial/unknown outcomes with an injected clock.
  expect(["armed", "filled", "waiting-for-opening", "expired", "blocked"]).toContain(purchase.state);
  const visibleState = purchase.state === "blocked" ? (purchase.reserved > 0 ? "Armed · blocked" : "Blocked draft") : purchase.state.replaceAll("-", " ");
  await expect(page.getByText(visibleState, { exact: true })).toBeVisible();
  execFileSync("bash", ["scripts/purchases.sh", "worker", "--once"], { env: process.env, timeout: 60000 });
  const repeated = await (await request.get("/api/purchases")).json();
  expect(repeated.purchases).toHaveLength(1);
  expect(repeated.purchases[0].intentId).toBe(purchase.intentId);
  await page.getByLabel("Company and listing").selectOption("anthropic-unconfirmed");
  await page.getByLabel("Whole shares").fill("1");
  await page.getByLabel("Provisional limit (USD)").fill("100");
  await page.getByLabel("Provisional spending ceiling (USD)").fill("105");
  await page.getByLabel("Purchase after").fill(wall(new Date(Date.now() + 60000)));
  await page.getByLabel("Stop if unfilled by").fill(wall(new Date(Date.now() + 3600000)));
  await page.getByRole("button", { name: "Preview purchase", exact: true }).click();
  await expect(page.getByText("This purchase cannot be armed yet.", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Save blocked draft", exact: true })).toBeVisible();
  await expect(page.locator("[aria-labelledby=preview-heading]")).toContainText("Exchange, share class and currency pending");
  await expect(page.locator("[aria-labelledby=preview-heading]")).not.toContainText("America/New_York");
  await page.getByRole("button", { name: "Save blocked draft", exact: true }).click();
  const unresolvedCard = page.locator("article").filter({ has: page.getByRole("heading", { name: "1 × Anthropic", exact: true }) });
  await expect(unresolvedCard.getByRole("button", { name: "Arm simulation", exact: true })).toBeDisabled();
  await unresolvedCard.getByRole("button", { name: "Edit draft", exact: true }).click();
  await expect(page.getByLabel("Provisional limit (USD)")).toHaveValue("100");
  await page.getByLabel("Provisional limit (USD)").fill("90");
  await page.getByLabel("Provisional spending ceiling (USD)").fill("95");
  await page.getByRole("button", { name: "Preview purchase", exact: true }).click();
  await page.getByRole("button", { name: "Save blocked draft changes", exact: true }).click();
  await expect(unresolvedCard).toContainText("90.00");
  await page.getByLabel("Company and listing").selectOption("d05-sgx");
  let nextSGX = new Date(Date.now() + 86400000);
  while (["Sat", "Sun"].includes(new Intl.DateTimeFormat("en-US", { timeZone: "Asia/Singapore", weekday: "short" }).format(nextSGX)) || ["01-01", "12-25"].includes(wall(nextSGX).slice(5, 10))) nextSGX = new Date(nextSGX.getTime() + 86400000);
  const sgxDate = wall(nextSGX).slice(0, 10);
  await page.getByLabel("Purchase after").fill(`${sgxDate}T09:00`);
  await page.getByLabel("Stop if unfilled by").fill(`${sgxDate}T16:00`);
  await page.getByLabel("Limit per share (SGD)").fill("100");
  await page.getByLabel("Total spending ceiling (SGD)").fill("105");
  await page.getByRole("button", { name: "Preview purchase", exact: true }).click();
  await expect(page.getByText("Within the simulation's supported limits.")).toBeVisible();
  await page.getByLabel("When to buy").selectOption("first-trade");
  await page.getByRole("button", { name: "Preview purchase", exact: true }).click();
  await expect(page.getByText("This listing does not support the selected trigger.")).toBeVisible();
  await page.getByRole("button", { name: "Stop all purchases", exact: true }).click();
  await expect(page.getByRole("button", { name: "Allow new purchases", exact: true })).toBeVisible();
  await expect(page.getByText(/All purchases stopped\./)).toContainText("No cancellations pending.");
  await page.getByRole("button", { name: "Allow new purchases", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("link", { name: "← Cockpit" }).click();
  await page.getByRole("link", { name: "Buy shares" }).click();
  await expect(page.getByRole("heading", { name: "2 × Apple" })).toBeVisible();
  await page.getByLabel("Timezone", { exact: true }).selectOption("America/New_York");
  await page.getByLabel("Limit per share (USD)").fill("101");
  await page.getByLabel("Total spending ceiling (USD)").fill("106");
  for (const local of ["2026-03-08T02:30", "2026-11-01T01:30"]) {
    await page.getByLabel("Purchase after").fill(local);
    await page.getByLabel("Stop if unfilled by").fill("2027-01-01T16:00");
    await page.getByRole("button", { name: "Preview purchase", exact: true }).click();
    await expect(page.getByRole("alert").filter({ hasText: "skipped or repeated by daylight saving" })).toBeVisible();
  }
  const unavailable = async (route: import("@playwright/test").Route) => {
    if (route.request().method() === "GET") await route.fulfill({ status: 503, json: { error: "Test service unavailable." } });
    else await route.continue();
  };
  await page.route("**/api/purchases", unavailable);
  await page.getByRole("button", { name: "Refresh status", exact: true }).click();
  await expect(page.getByText("Test service unavailable.", { exact: false })).toBeVisible();
  await expect(page.getByRole("heading", { name: "2 × Apple" })).toBeVisible();
  await page.unroute("**/api/purchases", unavailable);
  await page.getByRole("button", { name: "Reload saved purchases", exact: true }).click();
  await expect(page.getByText("Test service unavailable.", { exact: false })).toHaveCount(0);
  expect((await (await request.get("/api/purchases")).json()).purchases).toHaveLength(2);
  expect(pageErrors).toEqual([]);
});
